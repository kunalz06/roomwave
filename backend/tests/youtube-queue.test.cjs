'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const {createYouTubeQueue,MAX_QUEUE}=require('../youtube-queue.cjs');
const a='M7lc1UVf-VE',b='dQw4w9WgXcQ',c='9bZkp7q19f0';
test('first submitted video becomes current; other submissions form an editable queue',()=>{
  const q=createYouTubeQueue();q.setup('BCDEFG');
  assert.equal(q.add('BCDEFG',a,'Alice'),true);
  assert.equal(q.snapshot('BCDEFG').youtube.videoId,a);
  assert.equal(q.snapshot('BCDEFG').youtube.playing,false);
  assert.equal(q.snapshot('BCDEFG').queue.length,0);
  assert.equal(q.add('BCDEFG',b,'Bob'),true);
  assert.equal(q.add('BCDEFG',c,'Charlie'),true);
  assert.equal(q.add('BCDEFG','https://youtube.com/watch?v='+a,'Eve'),false);
  const original=q.snapshot('BCDEFG').queue;
  assert.equal(original.length,2);
  assert.equal(original[0].by,'Bob');
  assert.equal(q.move('BCDEFG',original[1].id,-1),true);
  assert.equal(q.snapshot('BCDEFG').queue[0].videoId,c);
  assert.equal(q.select('BCDEFG',original[1].id),true);
  assert.equal(q.snapshot('BCDEFG').youtube.videoId,c);
  assert.equal(q.snapshot('BCDEFG').youtube.playing,false);
  assert.equal(q.remove('BCDEFG',original[0].id),true);
  assert.equal(q.snapshot('BCDEFG').queue.length,0);
  q.removeRoom('BCDEFG');
  assert.equal(q.snapshot('BCDEFG'),null);
});
test('sequential automatic next, manual hold, repeat one and shuffle',()=>{
  let timestamp=1000;
  const q=createYouTubeQueue({now:()=>timestamp,random:n=>n-1});q.setup('BCDEFG');
  for(const id of [a,b,c])assert.equal(q.add('BCDEFG',id,'Host'),true);
  assert.equal(q.snapshot('BCDEFG').youtube.videoId,a);
  timestamp+=2500;
  assert.equal(q.snapshot('BCDEFG').youtube.position,2.5);
  assert.equal(q.next('BCDEFG',true),true);
  assert.equal(q.snapshot('BCDEFG').youtube.videoId,b);
  q.setMode('BCDEFG','repeat-one');
  timestamp+=1500;
  q.next('BCDEFG',true);
  assert.equal(q.snapshot('BCDEFG').youtube.videoId,b);
  assert.equal(q.snapshot('BCDEFG').youtube.position,0);
  q.setMode('BCDEFG','manual');
  timestamp+=3000;
  q.next('BCDEFG',true);
  assert.equal(q.snapshot('BCDEFG').youtube.playing,false);
  assert.equal(q.snapshot('BCDEFG').youtube.position,3);
  timestamp+=5000;
  assert.equal(q.snapshot('BCDEFG').youtube.position,3);
  assert.equal(q.snapshot('BCDEFG').queue.length,1);
  q.setMode('BCDEFG','shuffle');
  q.add('BCDEFG',b,'Host');
  q.next('BCDEFG');
  assert.equal(q.snapshot('BCDEFG').youtube.videoId,b);
  assert.equal(q.setMode('BCDEFG','invalid'),false);
});
test('queue limits and validation reject unsafe content and invalid state',()=>{
  const q=createYouTubeQueue();q.setup('BCDEFG');
  assert.equal(q.add('BCDEFG',a,'Guest'),true);
  for(let i=0;i<MAX_QUEUE;i++) assert.equal(q.add('BCDEFG',a,'Guest'),true);
  assert.equal(q.add('BCDEFG',a,'Guest'),false);
  assert.equal(q.move('BCDEFG','unrecognized',-1),false);
  assert.equal(q.setPlayback('BCDEFG',{videoId:'bad',position:0,playing:true}),false);
  assert.equal(q.setPlayback('BCDEFG',{videoId:a,position:999999,playing:true}),false);
  assert.equal(q.snapshot('BCDEFG').queue.length,MAX_QUEUE);
});
