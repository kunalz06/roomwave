'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const {createYouTubeQueue,MAX_QUEUE}=require('../youtube-queue.cjs');
const a='M7lc1UVf-VE',b='dQw4w9WgXcQ',c='9bZkp7q19f0';
test('everyone can submit links, queue accepts only video IDs, and host can reorder/select',()=>{
  const q=createYouTubeQueue();q.setup('ABCDEF');
  assert.equal(q.add('ABCDEF',a,'Alice'),true);
  assert.equal(q.add('ABCDEF',b,'Bob'),true);
  assert.equal(q.add('ABCDEF','https://youtube.com/watch?v='+a,'Eve'),false);
  let state=q.snapshot('ABCDEF');
  assert.equal(state.queue.length,2);
  assert.equal(state.queue[0].by,'Alice');
  assert.equal(state.youtube,null);
  const first=state.queue[0].id,second=state.queue[1].id;
  assert.equal(q.move('ABCDEF',second,-1),true);
  assert.equal(q.snapshot('ABCDEF').queue[0].id,second);
  assert.equal(q.select('ABCDEF',second),true);
  assert.equal(q.snapshot('ABCDEF').youtube.videoId,b);
  assert.equal(q.snapshot('ABCDEF').queue.length,1);
  assert.equal(q.remove('ABCDEF',first),true);
  assert.equal(q.snapshot('ABCDEF').queue.length,0);
  q.removeRoom('ABCDEF');
  assert.equal(q.snapshot('ABCDEF'),null);
});
test('auto next, manual hold, repeat-one, shuffle and empty playlist',()=>{
  let timestamp=1000;
  const q=createYouTubeQueue({now:()=>timestamp,random:()=>1});q.setup('ABCDEF');
  for(const id of [a,b,c])q.add('ABCDEF',id,'Host');
  assert.equal(q.next('ABCDEF'),true);
  assert.equal(q.snapshot('ABCDEF').youtube.videoId,a);
  timestamp+=2500;
  assert.ok(q.snapshot('ABCDEF').youtube.position>=2.5);
  assert.equal(q.next('ABCDEF',true),true);
  assert.equal(q.snapshot('ABCDEF').youtube.videoId,b);
  q.setMode('ABCDEF','repeat-one');
  q.next('ABCDEF',true);
  assert.equal(q.snapshot('ABCDEF').youtube.videoId,b);
  assert.equal(q.snapshot('ABCDEF').youtube.position,0);
  q.setMode('ABCDEF','manual');
  q.next('ABCDEF',true);
  assert.equal(q.snapshot('ABCDEF').youtube.playing,false);
  assert.equal(q.snapshot('ABCDEF').queue.length,1);
  q.setMode('ABCDEF','shuffle');
  q.add('ABCDEF',b,'Host');
  q.next('ABCDEF');
  assert.equal(q.snapshot('ABCDEF').youtube.videoId,b);
  assert.equal(q.setMode('ABCDEF','invalid'),false);
});
test('server enforces queue bounds',()=>{
  const q=createYouTubeQueue();q.setup('ABCDEF');
  for(let i=0;i<MAX_QUEUE;i++)assert.equal(q.add('ABCDEF',a,'Guest'),true);
  assert.equal(q.add('ABCDEF',a,'Guest'),false);
  assert.equal(q.move('ABCDEF','unrecognized',-1),false);
  assert.equal(q.setPlayback('ABCDEF',{videoId:'bad',position:0,playing:true}),false);
  assert.equal(q.setPlayback('ABCDEF',{videoId:a,position:999999,playing:true}),false);
});
